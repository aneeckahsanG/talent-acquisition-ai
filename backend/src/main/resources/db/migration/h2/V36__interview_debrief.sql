-- AI debrief of a candidate's interview scorecards for one role. Regenerating replaces the row;
-- fingerprint is a hash of the scorecards it was based on, so a later scorecard marks it out of date.
CREATE TABLE interview_debrief (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id        BIGINT       NOT NULL,
    requisition_id      BIGINT       NOT NULL,
    fingerprint         VARCHAR(64)  NOT NULL,
    recommendation      VARCHAR(30)  NOT NULL,
    confidence          VARCHAR(10)  NOT NULL,
    summary             TEXT         NOT NULL,
    details_json        TEXT         NOT NULL,
    suggested_next_step TEXT,
    guardrail_note      TEXT,
    generated_by        VARCHAR(100),
    generated_at        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_interview_debrief UNIQUE (candidate_id, requisition_id)
);
