CREATE TABLE interview_slot (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    start_time   TIMESTAMP NOT NULL,
    end_time     TIMESTAMP NOT NULL,
    interview_id BIGINT,
    CONSTRAINT uq_interview_slot_start UNIQUE (start_time),
    CONSTRAINT fk_slot_interview FOREIGN KEY (interview_id) REFERENCES interview_schedule(id)
);
