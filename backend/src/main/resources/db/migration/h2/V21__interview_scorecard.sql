CREATE TABLE interview_scorecard (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    interview_id    BIGINT        NOT NULL UNIQUE,
    technical       INT           NOT NULL,
    communication   INT           NOT NULL,
    problem_solving INT           NOT NULL,
    culture_fit     INT           NOT NULL,
    verdict         VARCHAR(20)   NOT NULL,
    notes           TEXT,
    submitted_by    BIGINT,
    submitted_at    TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_scorecard_interview FOREIGN KEY (interview_id) REFERENCES interview_schedule(id)
);
