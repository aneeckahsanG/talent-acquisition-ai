-- Who searched for or opened which candidate (candidate details are personal data)
CREATE TABLE candidate_access_log (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(100) NOT NULL,
    action        VARCHAR(20)  NOT NULL,
    candidate_id  BIGINT,
    search_text   VARCHAR(200),
    result_count  INT,
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_candidate_access_candidate ON candidate_access_log(candidate_id);
