-- CV Inbox: records each CV processed from the SFTP drop-folder, the AI's
-- judgment (considered/excluded) and the full per-role score breakdown, so
-- HR can audit every automated decision with justification.
CREATE TABLE IF NOT EXISTS cv_inbox_item (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_name               VARCHAR(500) NOT NULL,
    candidate_id            BIGINT,
    decision                VARCHAR(20) NOT NULL,   -- CONSIDERED, EXCLUDED
    status                  VARCHAR(20) NOT NULL,   -- PROCESSED, FAILED
    best_requisition_id     BIGINT,
    best_requisition_title  VARCHAR(255),
    best_match_score        DECIMAL(5,2),
    best_rationale          TEXT,
    match_details_json      TEXT,
    error_message           TEXT,
    processed_at            TIMESTAMP NOT NULL DEFAULT NOW(),
    created_at              TIMESTAMP NOT NULL DEFAULT NOW()
);
