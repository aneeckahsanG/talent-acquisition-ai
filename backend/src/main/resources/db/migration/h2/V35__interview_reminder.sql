-- Reminders and chasers sent for an interview. One row per (interview, kind, ref) keeps each from going out twice;
-- ref is the booked slot for reminders, so a rescheduled interview gets fresh reminders.
CREATE TABLE interview_reminder (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    interview_id     BIGINT       NOT NULL,
    kind             VARCHAR(40)  NOT NULL,
    ref              VARCHAR(40)  NOT NULL DEFAULT '',
    recipient_email  VARCHAR(255),
    sent_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_interview_reminder UNIQUE (interview_id, kind, ref)
);
