-- One row per stage change, so a candidate's history shows every step in order.
-- pipeline_stage itself still holds only the current stage (one row per candidate and role).
CREATE TABLE pipeline_stage_history (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id   BIGINT NOT NULL REFERENCES candidate(id) ON DELETE CASCADE,
    requisition_id BIGINT NOT NULL REFERENCES job_requisition(id) ON DELETE CASCADE,
    from_stage     VARCHAR(30),
    to_stage       VARCHAR(30) NOT NULL,
    changed_by     VARCHAR(50),
    notes          VARCHAR(65535),
    occurred_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_stage_history_candidate ON pipeline_stage_history(candidate_id);

-- Backfill what existing data can prove. Earlier moves were overwritten, so only two steps can be rebuilt:
-- the screening (a screening result exists for anyone who got past it) and the current stage.
INSERT INTO pipeline_stage_history (candidate_id, requisition_id, from_stage, to_stage, changed_by, notes, occurred_at)
SELECT ps.candidate_id, ps.requisition_id, NULL, 'SCREENED', 'SCREENING',
       'Screening recommendation: ' || sr.recommendation || ' (overall score: ' || sr.overall_score || ')',
       LEAST(sr.created_at, DATEADD('SECOND', -1, ps.entered_at))
FROM pipeline_stage ps
JOIN screening_result sr ON sr.candidate_id = ps.candidate_id AND sr.requisition_id = ps.requisition_id
WHERE ps.stage IN ('SHORTLISTED', 'INTERVIEW_SCHEDULED', 'OFFER', 'HIRED', 'NO_SHOW');

-- The current step. A leftover screening note on a later stage described the screening, not this step.
INSERT INTO pipeline_stage_history (candidate_id, requisition_id, from_stage, to_stage, changed_by, notes, occurred_at)
SELECT ps.candidate_id, ps.requisition_id,
       CASE WHEN ps.stage IN ('SHORTLISTED', 'INTERVIEW_SCHEDULED', 'OFFER', 'HIRED', 'NO_SHOW')
                 AND EXISTS (SELECT 1 FROM screening_result sr
                             WHERE sr.candidate_id = ps.candidate_id AND sr.requisition_id = ps.requisition_id)
            THEN 'SCREENED' END,
       ps.stage, ps.updated_by_agent,
       CASE WHEN ps.notes LIKE 'Screening recommendation%' AND ps.stage NOT IN ('SCREENED', 'REJECTED') THEN NULL ELSE ps.notes END,
       ps.entered_at
FROM pipeline_stage ps;
