-- Exact letter (and terms) each time an offer email is sent, so we can always show what the candidate saw
CREATE TABLE offer_letter (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    offer_id      BIGINT        NOT NULL,
    letter_text   TEXT          NOT NULL,
    salary_amount DECIMAL(12,2),
    currency      VARCHAR(10),
    start_date    DATE,
    expiry_date   DATE,
    sent_at       TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_offer_letter_offer FOREIGN KEY (offer_id) REFERENCES offer(id)
);

